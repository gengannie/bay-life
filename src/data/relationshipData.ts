export function getNpcDialogueExchange(
  npcId: string,
  kind: NpcInteractionKind,
  score: number,
  count: number
): NpcDialogueExchange {
  const bank = NPC_DIALOGUE_BANK[npcId] || NPC_DIALOGUE_BANK.npc_maya;
  const list = bank[kind] || bank.linkedin;
  const index = (count + Math.floor(score / 25)) % list.length;
  return list[index];
}

